// Uploads web/ to HoboHost over FTPS, plus a generated api/_private/config.php
// holding the API key and access token from .env. Only ever writes inside FTP_DIR.
//
//   npm run deploy            upload
//   npm run deploy -- --dry   list what would be uploaded, connect nothing
//
// Settings come from .env (see .env.example). FTP_TLS_NAME is the name the
// server's certificate is issued to, when it differs from FTP_HOST (on shared
// hosting it's the server's own name). The certificate is always verified.

import { Client } from "basic-ftp";
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { join, relative, posix } from "node:path";
import { Readable } from "node:stream";

const dry = process.argv.includes("--dry");

/**
 * Reads .env literally: KEY=value, split at the first "=", one pair of matching
 * outer quotes removed. Unlike Node's loadEnvFile, a "#" inside a value is kept,
 * so passwords containing "#" survive.
 */
function readEnvFile(path: string): Record<string, string> {
  if (!existsSync(path)) return {};
  const out: Record<string, string> = {};
  for (const line of readFileSync(path, "utf8").split(/\r?\n/)) {
    if (!line.trim() || line.trimStart().startsWith("#") || !line.includes("=")) continue;
    const at = line.indexOf("=");
    let value = line.slice(at + 1).trim();
    if (value.length >= 2 && value[0] === value.at(-1) && `'"`.includes(value[0])) value = value.slice(1, -1);
    out[line.slice(0, at).trim()] = value;
  }
  return out;
}

const fileEnv = readEnvFile(".env");
const env = (name: string, fallback = ""): string => (fileEnv[name] ?? process.env[name] ?? fallback).trim();
const host = env("FTP_HOST");
const port = Number(env("FTP_PORT", "21"));
const user = env("FTP_USER");
const password = fileEnv.FTP_PASSWORD ?? process.env.FTP_PASSWORD ?? "";
const tlsName = env("FTP_TLS_NAME") || host;
const remoteRoot = env("FTP_DIR").replace(/^\/+|\/+$/g, "");
const siteUrl = env("FTP_URL").replace(/\/+$/, "");
const provider = env("LLM_PROVIDER", "gemini");
const accessToken = env("ACCESS_TOKEN");
const providers: Record<string, { key: string; model: string; thinking: string }> = {
  gemini: {
    key: env("GEMINI_API_KEY"),
    model: env("GEMINI_MODEL", "gemini-flash-lite-latest"),
    thinking: env("GEMINI_THINKING_LEVEL"),
  },
  anthropic: { key: env("ANTHROPIC_API_KEY"), model: env("NARRATION_MODEL", "claude-sonnet-5-5"), thinking: "" },
};
const llm = providers[provider] ?? fail(`LLM_PROVIDER must be one of: ${Object.keys(providers).join(", ")}`);
const apiKey = llm.key;
const model = llm.model;

function fail(message: string): never {
  console.error(`deploy: ${message}`);
  process.exit(1);
}

if (!host || !user || !password) fail("FTP_HOST, FTP_USER and FTP_PASSWORD must be set in .env");
// An empty FTP_DIR would upload into the FTP account's root, which on our host is
// an existing website. Refuse rather than overwrite it.
if (!remoteRoot) fail("FTP_DIR must name a subfolder (e.g. guide), not the account root");
if (apiKey && accessToken.length < 24) {
  fail("ACCESS_TOKEN must be at least 24 characters once an API key is set: the relay uses your quota and money for anyone who has it");
}

/** PHP single-quoted string literal. */
const php = (value: string): string => `'${value.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;

const configPhp = `<?php
// Generated by scripts/deploy.ts from .env. Do not edit on the server.
return [
  'provider' => ${php(provider)},
  'api_key' => ${php(apiKey)},
  'access_token' => ${php(accessToken)},
  'model' => ${php(model)},
  'thinking' => ${php(llm.thinking)},
  'max_tokens' => 4000,
  'daily_calls' => 300,
  'max_body_bytes' => 65536,
];
`;

function listFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? listFiles(path) : [path];
  });
}

const localRoot = "web";
// Type declarations are for the type checker only; the site doesn't need them.
const files = listFiles(localRoot)
  .map((path) => relative(localRoot, path).split("\\").join("/"))
  .filter((file) => !file.endsWith(".d.ts"));

console.log(`deploy: ${files.length} files from ${localRoot}/ + api/_private/config.php → ${host}:/${remoteRoot}/`);
console.log(`deploy: ${provider} ${model}, API key ${apiKey ? "set" : "NOT set (the relay will answer 503)"}`);
if (dry) {
  for (const file of files) console.log(`  ${file}`);
  process.exit(0);
}

const client = new Client(30_000);
try {
  await client.access({
    host,
    port,
    user,
    password,
    secure: true,
    // Verify the certificate against the name it is issued to.
    secureOptions: { host: tlsName, servername: tlsName },
  });

  const dirs = [...new Set(files.map((file) => posix.dirname(file)))].sort();
  for (const dir of dirs) {
    await client.ensureDir(posix.join("/", remoteRoot, dir === "." ? "" : dir));
  }
  for (const file of files) {
    await client.uploadFrom(join(localRoot, file), posix.join("/", remoteRoot, file));
    console.log(`  ↑ ${file}`);
  }
  await client.ensureDir(posix.join("/", remoteRoot, "api/_private"));
  await client.uploadFrom(Readable.from([configPhp]), posix.join("/", remoteRoot, "api/_private/config.php"));
  console.log("  ↑ api/_private/config.php (generated)");
} catch (error) {
  const message = error instanceof Error ? error.message : String(error);
  fail(password ? message.split(password).join("***") : message);
} finally {
  client.close();
}

if (siteUrl) {
  const res = await fetch(`${siteUrl}/api/ping.php`).catch((error: unknown) => error as Error);
  if (res instanceof Error) console.log(`deploy: uploaded, but ${siteUrl}/api/ping.php failed: ${res.message}`);
  else console.log(`deploy: ${siteUrl}/api/ping.php → ${res.status} ${await res.text()}`);
}
